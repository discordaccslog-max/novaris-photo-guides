/*
  Writes field-kit/sw.js. The version is a hash of every cached file, so any
  change to the Field Kit produces a new service worker that refreshes the cache.
*/
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

export function makeServiceWorker(root) {
  const list = (dir) => fs.readdirSync(path.join(root, dir)).filter((f) => !f.startsWith(".")).flatMap((f) => {
    const rel = path.posix.join(dir, f);
    return fs.statSync(path.join(root, rel)).isDirectory() ? list(rel) : [rel];
  });
  const fieldKit = list("field-kit").filter((f) => f !== "field-kit/sw.js");
  const shared = ["js/site-config.js", "js/products.js", "js/license.js", "js/license-store.js", "js/pdf.js", "js/exposure.js", "js/sun.js", "favicon.svg"];
  const fonts = list("fonts").filter((f) => /\.(css|woff2)$/.test(f));
  const files = [...fieldKit, ...shared, ...fonts].sort();
  const hash = crypto.createHash("sha256");
  for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
  const version = hash.digest("hex").slice(0, 12);
  const assets = ["/field-kit/", ...files.map((f) => "/" + f)];

  const sw = `/* Novaris Field Kit service worker (generated by tools/make-sw.js). */
const VERSION = "${version}";
const CACHE = "nfk-" + VERSION;
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map((url) => new Request(url, { cache: "reload" })))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("nfk-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error("timeout")), ms);
    promise.then((r) => { clearTimeout(t); resolve(r); }, (e) => { clearTimeout(t); reject(e); });
  });
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Field Kit pages: try the network briefly, fall back to the cached app shell.
  if (req.mode === "navigate" && url.pathname.startsWith("/field-kit/")) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const res = await withTimeout(fetch(req), 3500);
        if (res.ok) cache.put("/field-kit/", res.clone());
        return res;
      } catch {
        return (await cache.match("/field-kit/")) || (await cache.match("/field-kit/index.html")) || Response.error();
      }
    })());
    return;
  }

  // Cached files: serve from the cache straight away and refresh it in the background.
  if (ASSETS.includes(url.pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(url.pathname);
      const network = fetch(req).then((res) => { if (res.ok) cache.put(url.pathname, res.clone()); return res; }).catch(() => null);
      if (cached) { event.waitUntil(network); return cached; }
      return (await network) || Response.error();
    })());
  }
});
`;
  fs.writeFileSync(path.join(root, "field-kit/sw.js"), sw);
  return { version, count: assets.length };
}
